import argparse
import json
import os
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import classification_report, f1_score
from sklearn.preprocessing import StandardScaler
from sklearn.utils.class_weight import compute_class_weight
import xgboost as xgb
import onnx
from onnx import helper, numpy_helper

from splits import temporal_purged_split


INFERENCE_TS = """// GENERATED by trainer.py - DO NOT EDIT
// Model parameters for {{MODEL_NAME}} (horizon={{HORIZON}}d)
// Last trained: {{DATE}}

export interface ModelWeights {
  xgbThreshold: number
  featureImportance: Record<string, number>
  scalerMean: Record<string, number>
  scalerStd: Record<string, number>
}

export const model: ModelWeights = {
  xgbThreshold: {{THRESHOLD}},
  featureImportance: {{FEATURE_IMPORTANCE}},
  scalerMean: {{SCALER_MEAN}},
  scalerStd: {{SCALER_STD}},
}
"""

FEATURE_COLS = [
    'features.rsi',
    'features.historyChange30d',
    'features.dayChange',
    'features.volumeRatio',
    'features.priceToSma20',
    'features.priceToSma50',
    'features.atr',
    'features.newsImpactScore',
    'features.signalCount',
    'features.marketCap',
    'features.peRatio',
    'features.dividendYield',
]


def flatten_sample(sample: dict) -> dict:
    flat = {}
    for key, val in _flatten(sample, ''):
        flat[key] = val
    return flat


def _flatten(obj: dict, prefix: str):
    for k, v in obj.items():
        full_key = f'{prefix}.{k}' if prefix else k
        if isinstance(v, dict):
            yield from _flatten(v, full_key)
        else:
            yield full_key, v


def load_data(data_dir: str) -> pd.DataFrame:
    files = sorted(Path(data_dir).glob('training_*.jsonl'))
    if not files:
        print(f'No training files found in {data_dir}')
        sys.exit(1)

    rows = []
    for f in files:
        with open(f) as fh:
            for line in fh:
                line = line.strip()
                if line:
                    rows.append(flatten_sample(json.loads(line)))

    df = pd.DataFrame(rows)
    print(f'Loaded {len(df)} samples from {len(files)} files')
    return df


def to_action(ret_col: str, df: pd.DataFrame) -> pd.Series:
    col = f'labels.{ret_col}'
    mask_not_null = df[col].notna()
    actions = pd.Series('hold', index=df.index)
    actions[mask_not_null & (df[col] > 3.0)] = 'buy'
    actions[mask_not_null & (df[col] < -3.0)] = 'sell'
    actions[~mask_not_null] = 'hold'
    return actions


def prepare_data(df: pd.DataFrame, horizon: int = 5) -> tuple:
    ret_col = f'return_{horizon}d'
    df = df.dropna(subset=[f'labels.{ret_col}']).copy()
    df['action'] = to_action(ret_col, df)

    # map actions to numeric
    action_map = {'sell': 0, 'hold': 1, 'buy': 2}
    df['action_num'] = df['action'].map(action_map)

    X = pd.DataFrame()
    for col in FEATURE_COLS:
        clean_col = col.replace('features.', '')
        if col in df.columns:
            X[clean_col] = pd.to_numeric(df[col], errors='coerce')
        else:
            X[clean_col] = np.nan

    # NaN preservados: a imputacao usa a mediana do TREINO (em main) para nao vazar informacao da validacao.
    y = df['action_num'].values
    tickers = df['ticker'].values
    timestamps = df['timestamp'].values

    return X, y, tickers, timestamps


def train_xgb(X_train, y_train, X_val, y_val):
    classes = np.unique(y_train)
    class_weights = compute_class_weight('balanced', classes=classes, y=y_train)
    sample_weight = np.array([class_weights.tolist()[int(c)] for c in y_train])

    model = xgb.XGBClassifier(
        n_estimators=300,
        max_depth=6,
        learning_rate=0.05,
        subsample=0.8,
        colsample_bytree=0.8,
        reg_alpha=0.1,
        reg_lambda=1.0,
        eval_metric='mlogloss',
        early_stopping_rounds=30,
        random_state=42,
        n_jobs=-1,
    )

    model.fit(
        X_train, y_train,
        sample_weight=sample_weight,
        eval_set=[(X_val, y_val)],
        verbose=False,
    )

    train_pred = model.predict(X_train)
    val_pred = model.predict(X_val)

    print('\nTraining set:')
    print(classification_report(y_train, train_pred, target_names=['sell', 'hold', 'buy']))
    print('\nValidation set:')
    print(classification_report(y_val, val_pred, target_names=['sell', 'hold', 'buy']))

    f1 = f1_score(y_val, val_pred, average='weighted')
    print(f'\nValidation weighted F1: {f1:.4f}')

    return model, f1


def export_model(model, X, horizon: int, model_dir: str, scaler):
    model_path = Path(model_dir) / f'xgb_horizon_{horizon}d.json'
    model.save_model(str(model_path))
    print(f'Model saved to {model_path}')

    # export onnx for serving
    onnx_path = Path(model_dir) / f'xgb_horizon_{horizon}d.onnx'
    try:
        model.get_booster().save_model(str(onnx_path))
        print(f'ONNX model saved to {onnx_path}')
    except Exception as e:
        print(f'ONNX export failed: {e}')

    # feature importance
    importance = model.feature_importances_
    feature_names = model.get_booster().feature_names or X.columns.tolist()
    feat_imp = {name: float(imp) for name, imp in zip(feature_names, importance)
                if imp > 0.01}
    sorted_imp = dict(sorted(feat_imp.items(), key=lambda x: -x[1])[:15])

    # scaler params
    scaler_mean = {col: float(m) for col, m in zip(X.columns, scaler.mean_)}
    scaler_std = {col: float(s) for col, s in zip(X.columns, scaler.scale_)}

    # find best threshold from validation
    threshold = 0.55

    ts_code = (
        INFERENCE_TS
        .replace('{{MODEL_NAME}}', f'xgb_horizon_{horizon}d')
        .replace('{{HORIZON}}', str(horizon))
        .replace('{{DATE}}', pd.Timestamp.now().strftime('%Y-%m-%d %H:%M:%S'))
        .replace('{{THRESHOLD}}', str(threshold))
        .replace('{{FEATURE_IMPORTANCE}}', json.dumps(sorted_imp, indent=2))
        .replace('{{SCALER_MEAN}}', json.dumps(scaler_mean, indent=2))
        .replace('{{SCALER_STD}}', json.dumps(scaler_std, indent=2))
    )

    ts_path = Path(model_dir) / f'model_horizon_{horizon}d.ts'
    with open(ts_path, 'w') as f:
        f.write(ts_code)
    print(f'TypeScript model file saved to {ts_path}')


def main():
    parser = argparse.ArgumentParser(description='Dinheirama training pipeline')
    parser.add_argument('--data-dir', default='/data/training',
                        help='Directory with training_*.jsonl files')
    parser.add_argument('--model-dir', default='/data/models',
                        help='Output directory for trained models')
    parser.add_argument('--horizon', type=int, default=5,
                        help='Prediction horizon in days')
    parser.add_argument('--test-size', type=float, default=0.2)
    args = parser.parse_args()

    os.makedirs(args.model_dir, exist_ok=True)

    df = load_data(args.data_dir)

    X, y, tickers, timestamps = prepare_data(df, horizon=args.horizon)
    print(f'Features: {X.shape[1]}')
    print(f'Samples with labels: {len(X)}')

    if len(X) < 100:
        print('Not enough labeled samples. Collect more data.')
        sys.exit(1)

    # Divisao temporal com purga: treino = passado, validacao = futuro; rotulos que olham para dentro da
    # janela de validacao saem do treino. Dividir por ticker vazava o fator de mercado (mesmas datas).
    train_idx, val_idx = temporal_purged_split(timestamps, test_size=args.test_size, horizon_days=args.horizon)
    X_train, X_val = X.iloc[train_idx], X.iloc[val_idx]
    y_train, y_val = y[train_idx], y[val_idx]

    medians = X_train.median()
    X_train = X_train.fillna(medians)
    X_val = X_val.fillna(medians)

    print(f'Train: {len(X_train)} samples | Val: {len(X_val)} samples')

    scaler = StandardScaler()
    X_train_scaled = scaler.fit_transform(X_train)
    X_val_scaled = scaler.transform(X_val)

    model, f1 = train_xgb(
        X_train_scaled, y_train,
        X_val_scaled, y_val,
    )

    export_model(model, X, args.horizon, args.model_dir, scaler)

    # save horizon as metadata
    meta = {'horizon': args.horizon, 'f1_score': float(f1),
            'samples': len(X), 'features': FEATURE_COLS}
    meta_path = Path(args.model_dir) / 'model_metadata.json'
    with open(meta_path, 'w') as f:
        json.dump(meta, f, indent=2)
    print(f'Metadata saved to {meta_path}')


if __name__ == '__main__':
    main()
